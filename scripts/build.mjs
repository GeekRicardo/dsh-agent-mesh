// dsh-agent-mesh build — generates lib/index.js from src/mesh.dynamic.js.
//
// The engine was developed as a DYNAMIC Cordis package body evaluated with a
// few ambient globals (`harness`, `console`). This build wraps that exact body
// in the formal bundle container instead of rewriting it, so what ships is what
// was tested. The container supplies the two things the dynamic sandbox gave
// ambiently: the `harness` tool DSL (defineTool / registerTool) and ES module
// packaging.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8')
const write = (rel, text) => {
  fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true })
  fs.writeFileSync(path.join(root, rel), text)
  console.log('built', rel, `(${Buffer.byteLength(text)} bytes)`)
}

const meshBody = read('src/mesh.dynamic.js')

const indexJs = `// dsh-agent-mesh — host half (generated by scripts/build.mjs, do not edit).
//
// One conversation opens, drives, approves and configures OTHER conversations,
// all landing in dsh's own durable session vocabulary. The engine body below is
// byte-identical to the dynamic package it was developed as; this file only
// supplies the tool DSL (\`defineTool\` / \`registerTool\`, which dsh's own
// compiler provides for a bundle a package cannot resolve) and module packaging.

const inject = ['webServer', 'subprocess', 'timer']

function meshHalf(harness, meshExtension) {
${meshBody}
}

/**
 * Compile the parameter DSL into the JSON Schema \`ctx.tools.register\` expects —
 * what \`harness.defineTool\` did for the dynamic package. Requiredness is a
 * per-property annotation there and a root array here; the root stays open,
 * exactly as dsh's own compiler leaves it.
 */
function toParameterSchema(parameters) {
  const properties = {}
  const required = []
  for (const key of Object.keys(parameters || {})) {
    const spec = parameters[key]
    const property = {}
    for (const field of Object.keys(spec)) {
      if (field === 'required') continue
      property[field] = spec[field]
    }
    if (spec.required === true) required.push(key)
    properties[key] = property
  }
  return { type: 'object', properties, ...(required.length === 0 ? {} : { required }) }
}

/** \`{ type: 'json' }\` means "any lossless JSON value", which is the empty schema. */
function toValueSchema(schema) {
  if (schema !== null && typeof schema === 'object' && schema.type === 'json') {
    const rest = { ...schema }
    delete rest.type
    return rest
  }
  return schema
}

function apply(ctx) {
  const harness = {
    defineTool: (definition) => ({
      ...definition,
      parameters: toParameterSchema(definition.parameters),
      output: { ...definition.output, schema: toValueSchema(definition.output.schema) },
    }),
    registerTool: (target, tool) => {
      const tools = target.get('tools')
      if (tools === undefined) return () => {}
      return tools.register(tool)
    },
  }
  return meshHalf(harness).apply(ctx)
}

export { apply, inject }
`

write('lib/index.js', indexJs)
